CREATE TABLE appointments (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  appointment_type TEXT DEFAULT 'general' CHECK(appointment_type IN ('general','doctor','business','personal')),
  start_datetime TEXT NOT NULL,
  end_datetime TEXT NOT NULL,
  all_day_event INTEGER DEFAULT 0,
  location TEXT,
  is_virtual INTEGER DEFAULT 0,
  meeting_link TEXT,
  meeting_platform TEXT,
  status TEXT DEFAULT 'scheduled' CHECK(status IN ('scheduled','confirmed','cancelled','completed','rescheduled')),
  reminder_minutes_before INTEGER DEFAULT 15 CHECK(reminder_minutes_before BETWEEN 0 AND 1440),
  is_recurring INTEGER DEFAULT 0,
  recurrence_pattern TEXT,
  calendar_color TEXT DEFAULT '#2196F3' CHECK(length(calendar_color) <= 7),
  external_event_id TEXT,
  external_sync_status TEXT DEFAULT 'not_synced',
  notes TEXT,
  is_deleted INTEGER DEFAULT 0,
  created_at TEXT DEFAULT (datetime('now')),
  updated_at TEXT DEFAULT (datetime('now')),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CHECK(start_datetime < end_datetime),
  CHECK(length(title) <= 255),
  CHECK(length(description) <= 4000),
  CHECK(length(location) <= 500),
  CHECK(length(meeting_link) <= 500),
  CHECK(length(meeting_platform) <= 50),
  CHECK(length(recurrence_pattern) <= 100),
  CHECK(length(notes) <= 4000)
);

CREATE TABLE participants (
  id TEXT PRIMARY KEY,
  appointment_id TEXT NOT NULL,
  user_id TEXT,
  email TEXT NOT NULL,
  full_name TEXT,
  invitation_status TEXT DEFAULT 'pending' CHECK(invitation_status IN ('pending','sent','accepted','declined','tentative')),
  participant_role TEXT DEFAULT 'attendee' CHECK(participant_role IN ('organizer','attendee','optional')),
  created_at TEXT DEFAULT (datetime('now')),
  updated_at TEXT DEFAULT (datetime('now')),
  FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  UNIQUE(appointment_id, email),
  CHECK(length(email) <= 255),
  CHECK(length(full_name) <= 100)
);