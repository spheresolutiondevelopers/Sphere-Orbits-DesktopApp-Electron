PRAGMA foreign_keys = ON;

CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  username TEXT UNIQUE,
  password_hash TEXT,
  password_salt TEXT,
  display_name TEXT,
  first_name TEXT,
  last_name TEXT,
  phone_number TEXT,
  avatar_url TEXT,
  date_of_birth TEXT,
  account_type TEXT NOT NULL DEFAULT 'free' CHECK(account_type IN ('free','premium','enterprise','admin')),
  is_active INTEGER NOT NULL DEFAULT 1,
  is_deleted INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  CHECK(length(email) <= 255),
  CHECK(length(username) <= 100),
  CHECK(length(display_name) <= 100),
  CHECK(length(first_name) <= 50),
  CHECK(length(last_name) <= 50),
  CHECK(length(phone_number) <= 20),
  CHECK(length(avatar_url) <= 500)
);

CREATE TABLE categories (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  category_name TEXT NOT NULL,
  category_type TEXT NOT NULL DEFAULT 'custom' CHECK(category_type IN ('system','custom')),
  description TEXT,
  color_code TEXT DEFAULT '#4CAF50' CHECK(length(color_code) <= 7),
  icon_name TEXT,
  category_order INTEGER DEFAULT 0,
  is_default INTEGER DEFAULT 0,
  is_deleted INTEGER DEFAULT 0,
  created_at TEXT DEFAULT (datetime('now')),
  updated_at TEXT DEFAULT (datetime('now')),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  UNIQUE(user_id, category_name),
  CHECK(length(category_name) <= 100),
  CHECK(length(description) <= 500)
);

CREATE TABLE tasks (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  task_type TEXT DEFAULT 'general' CHECK(task_type IN ('general','meeting','reminder','deadline','event')),
  priority_level TEXT DEFAULT 'medium' CHECK(priority_level IN ('low','medium','high','critical')),
  status TEXT DEFAULT 'pending' CHECK(status IN ('pending','in_progress','completed','cancelled','deferred')),
  completion_percentage INTEGER DEFAULT 0 CHECK(completion_percentage BETWEEN 0 AND 100),
  due_date TEXT,
  due_time TEXT,
  start_date TEXT,
  start_time TEXT,
  end_date TEXT,
  end_time TEXT,
  location_name TEXT,
  location_address TEXT,
  latitude REAL,
  longitude REAL,
  estimated_duration_minutes INTEGER,
  actual_duration_minutes INTEGER,
  time_spent_minutes INTEGER DEFAULT 0,
  is_recurring INTEGER DEFAULT 0,
  recurrence_rule TEXT,
  parent_task_id TEXT,
  external_id TEXT,
  external_source TEXT,
  external_sync_status TEXT DEFAULT 'not_synced',
  tags TEXT,
  notes TEXT,
  category_id TEXT,
  is_deleted INTEGER DEFAULT 0,
  created_at TEXT DEFAULT (datetime('now')),
  updated_at TEXT DEFAULT (datetime('now')),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (parent_task_id) REFERENCES tasks(id) ON DELETE SET NULL,
  FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL,
  CHECK(length(title) <= 255),
  CHECK(length(description) <= 4000),
  CHECK(length(location_name) <= 255),
  CHECK(length(location_address) <= 500),
  CHECK(length(tags) <= 500),
  CHECK(length(notes) <= 2000),
  CHECK(length(recurrence_rule) <= 500),
  CHECK(length(external_id) <= 255),
  CHECK(length(external_source) <= 50),
  CHECK(length(external_sync_status) <= 20)
);

CREATE TABLE subtasks (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  status TEXT DEFAULT 'pending' CHECK(status IN ('pending','in_progress','completed','cancelled')),
  priority TEXT DEFAULT 'medium' CHECK(priority IN ('low','medium','high')),
  due_date TEXT,
  due_time TEXT,
  completed_at TEXT,
  subtask_order INTEGER DEFAULT 0,
  is_deleted INTEGER DEFAULT 0,
  created_at TEXT DEFAULT (datetime('now')),
  updated_at TEXT DEFAULT (datetime('now')),
  FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
  CHECK(length(title) <= 255),
  CHECK(length(description) <= 1000)
);